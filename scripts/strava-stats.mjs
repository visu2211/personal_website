// Turns a Strava data export into assets/strava-data.js for the Running panel.
// Strava → Settings → My Account → Download or Delete Your Account → Request Your Archive (free).
// Run:  node scripts/strava-stats.mjs ~/Downloads/export_XXXXXXX.zip
// Only activities.csv is read from the zip; contacts, logins, and other files are never touched.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const IN = process.argv[2];
const OUT = process.argv[3] || 'assets/strava-data.js';
if (!IN) { console.error('Usage: node scripts/strava-stats.mjs <export.zip | activities.csv>'); process.exit(1); }

const text = IN.endsWith('.zip')
  ? execFileSync('unzip', ['-p', IN, 'activities.csv'], { maxBuffer: 64 * 1024 * 1024 }).toString('utf8')
  : readFileSync(IN, 'utf8');

function parseCSV(t) {
  const rows = []; let row = [], f = '', q = false;
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (q) { if (c === '"' && t[i + 1] === '"') { f += '"'; i++; } else if (c === '"') q = false; else f += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && t[i + 1] === '\n') i++; row.push(f); f = ''; if (row.length > 1) rows.push(row); row = []; }
    else f += c;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  return rows;
}

const [head, ...body] = parseCSV(text);
// The export repeats some headers (Distance, Elapsed Time). The later copies are the raw metric values.
const col = (name) => head.lastIndexOf(name);
const C = { date: head.indexOf('Activity Date'), name: head.indexOf('Activity Name'), type: head.indexOf('Activity Type'),
  moving: col('Moving Time'), dist: col('Distance'), elev: col('Elevation Gain'), id: head.indexOf('Activity ID') };

const MI = 1609.344;
let runs = body
  .filter((r) => /run/i.test(r[C.type]))
  .map((r) => ({
    id: r[C.id], name: r[C.name], date: new Date(r[C.date] + ' UTC'),
    meters: parseFloat(r[C.dist]) || 0, movingSec: parseFloat(r[C.moving]) || 0, elevM: parseFloat(r[C.elev]) || 0,
  }))
  .filter((r) => !isNaN(r.date) && r.meters > 0)
  .sort((a, b) => b.date - a.date);

// drop duplicate uploads: same start within 2 minutes and distance within 5%
runs = runs.filter((r, i) => !runs.slice(0, i).some((o) => Math.abs(o.date - r.date) < 120000 && Math.abs(o.meters - r.meters) / o.meters < 0.05));

const now = new Date();
const totals = (list) => ({
  runs: list.length,
  miles: +(list.reduce((s, r) => s + r.meters, 0) / MI).toFixed(1),
  hours: +(list.reduce((s, r) => s + r.movingSec, 0) / 3600).toFixed(1),
  elevFt: Math.round(list.reduce((s, r) => s + r.elevM, 0) * 3.28084),
});
const iso = (d) => d.toISOString().slice(0, 10);
const days = {};
for (const r of runs) if (now - r.date < 140 * 86400000) days[iso(r.date)] = +(((days[iso(r.date)] || 0) + r.meters / MI).toFixed(2));

const data = {
  live: false,
  generated: iso(now),
  recent: totals(runs.filter((r) => now - r.date < 28 * 86400000)),
  ytd: totals(runs.filter((r) => r.date.getUTCFullYear() === now.getUTCFullYear())),
  all: totals(runs),
  runs: runs.slice(0, 6).map((r) => ({
    name: r.name,
    date: r.date.toISOString(),
    miles: +(r.meters / MI).toFixed(2),
    movingSec: Math.round(r.movingSec),
    paceSecPerMi: Math.round(r.movingSec / (r.meters / MI)),
    elevFt: Math.round(r.elevM * 3.28084),
    url: `https://www.strava.com/activities/${r.id}`,
  })),
  days,
};

writeFileSync(OUT, `// Generated by scripts/strava-stats.mjs on ${data.generated} from a Strava export. Re-run after a new export.\nwindow.STRAVA = ${JSON.stringify(data, null, 2)};\n`);
console.log(`Wrote ${OUT}: ${data.all.runs} runs, ${data.all.miles} mi all time, ${data.recent.miles} mi in the last 4 weeks.`);
