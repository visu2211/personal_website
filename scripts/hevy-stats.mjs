// Turns a Hevy workout export into assets/hevy-data.js for the Training section.
// Hevy app → Profile → Settings → Export & Import Data → Export Workouts (free, no Pro needed).
// Save the CSV as data/hevy-workouts.csv, then run:  node scripts/hevy-stats.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const IN = process.argv[2] || 'data/hevy-workouts.csv';

// Lifts shown under "Best sets", in order. Use exact exercise names from Hevy.
// Leave empty to auto-pick your most-logged compound lifts.
const FEATURED = [
  'Squat (Barbell)',
  'Incline Bench Press (Smith Machine)',
  'Lat Pulldown (Cable)',
  'Shoulder Press (Dumbbell)',
];
const OUT = process.argv[3] || 'assets/hevy-data.js';

function parseCSV(text) {
  const rows = []; let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.length > 1 || row[0]) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), r[i] ?? ''])));
}

const MONTHS = { jan: 0, feb: 1, mar: 2, apr: 3, may: 4, jun: 5, jul: 6, aug: 7, sep: 8, oct: 9, nov: 10, dec: 11 };
function parseDate(s) {
  const m = s.match(/(\d{1,2}) (\w{3})\w* (\d{4}),? (\d{1,2}):(\d{2})/); // "6 Oct 2026, 18:02"
  if (m) return new Date(+m[3], MONTHS[m[2].toLowerCase()], +m[1], +m[4], +m[5]);
  const d = new Date(s);
  return isNaN(d) ? null : d;
}
const dayKey = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

const sets = parseCSV(readFileSync(IN, 'utf8'));
const kg = !('weight_lbs' in sets[0]) && 'weight_kg' in sets[0];
const lbs = (r) => { const w = parseFloat(kg ? r.weight_kg : r.weight_lbs) || 0; return kg ? w * 2.20462 : w; };

// group sets into workouts by start time
const byWorkout = new Map();
for (const r of sets) {
  const key = r.start_time + '|' + r.title;
  if (!byWorkout.has(key)) byWorkout.set(key, { title: r.title, start: parseDate(r.start_time), end: parseDate(r.end_time), sets: [] });
  byWorkout.get(key).sets.push(r);
}
const workouts = [...byWorkout.values()].filter((w) => w.start).sort((a, b) => b.start - a.start);

const work = (w) => w.sets.filter((s) => s.set_type !== 'warmup');
const volume = (w) => work(w).reduce((v, s) => v + lbs(s) * (parseInt(s.reps) || 0), 0);

// best set per exercise by estimated 1RM (Epley), reps capped at 12 to keep it meaningful
const best = new Map(), freq = new Map();
for (const w of workouts) for (const s of work(w)) {
  const wt = lbs(s), reps = parseInt(s.reps) || 0;
  if (!wt || !reps || reps > 12) continue;
  const e1rm = wt * (1 + reps / 30);
  freq.set(s.exercise_title, (freq.get(s.exercise_title) || 0) + 1);
  const b = best.get(s.exercise_title);
  if (!b || e1rm > b.e1rm) best.set(s.exercise_title, { exercise: s.exercise_title, weight: Math.round(wt), reps, e1rm: Math.round(e1rm), date: dayKey(w.start) });
}
const COMPOUND = /squat|bench|deadlift|press|row|pulldown|pull ?up|chin ?up|dip|lunge|hip thrust/i;
const ISOLATION = /curl|raise|fly|extension|pushdown|kickback|shrug/i;
const auto = [...freq.entries()].filter(([n]) => COMPOUND.test(n) && !ISOLATION.test(n)).sort((a, b) => b[1] - a[1]).map(([n]) => n);
const topLifts = (FEATURED.length ? FEATURED.filter((n) => best.has(n)) : auto).slice(0, 4).map((n) => best.get(n));

// last 20 weeks of training days for the heatmap
const days = {};
const cutoff = Date.now() - 20 * 7 * 86400000;
for (const w of workouts) if (w.start >= cutoff) days[dayKey(w.start)] = (days[dayKey(w.start)] || 0) + 1;

const now = new Date();
const data = {
  generated: dayKey(now),
  totalWorkouts: workouts.length,
  since: workouts.length ? dayKey(workouts.at(-1).start) : null,
  thisYear: workouts.filter((w) => w.start.getFullYear() === now.getFullYear()).length,
  last30: workouts.filter((w) => now - w.start < 30 * 86400000).length,
  totalVolumeLbs: Math.round(workouts.reduce((v, w) => v + volume(w), 0)),
  topLifts,
  recent: workouts.slice(0, 5).map((w) => ({
    title: w.title,
    date: dayKey(w.start),
    minutes: w.end ? Math.round((w.end - w.start) / 60000) : null,
    exercises: new Set(w.sets.map((s) => s.exercise_title)).size,
    sets: work(w).length,
    volumeLbs: Math.round(volume(w)),
  })),
  days,
};

writeFileSync(OUT, `// Generated by scripts/hevy-stats.mjs on ${data.generated}. Re-run after a new Hevy export.\nwindow.HEVY = ${JSON.stringify(data, null, 2)};\n`);
console.log(`Wrote ${OUT}: ${data.totalWorkouts} workouts, ${topLifts.length} top lifts, ${Object.keys(days).length} training days in the last 20 weeks.`);
